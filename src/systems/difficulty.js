// 难度旋钮：所有决定"这一局有多难"的常数集中在这一个文件里。
//
// 为什么集中：前两轮调平衡时数字散在 upgrades.js / run.js / meta.js 三处，
// 每次想看清"当前这一版的难度长什么样"都要翻三个文件，
// 而且很容易只改一处、漏掉另一处（第一轮就发生过：
// 血量曲线改了、终局 Boss 倍率没改，于是"最终决战"比一章普通怪还弱）。
//
// 集中之后，调平衡 = 改这一个文件 → 跑一次 `node scripts/balance.mjs` → 看报告。
//
// **每个数字都要能回答"它是怎么来的"**，注释里写清楚来源，
// 不要出现"感觉 1.25 差不多"这种话。

/**
 * 普通敌人每波增加的血量：`hp = 1 + floor((wave-1) * ENEMY_HP_PER_WAVE)`
 *
 * 来源（DECISIONS §11.2c）：
 * - 0.33（原值）：需求 11 DPS vs 保底火力 86 DPS —— 太松，机器人在第 14 波满血。
 * - 0.75：需求 57 DPS vs 保底 64 DPS —— **仍然松**，"什么都不选"也能打完。
 * - 1.25：需求 ≈ 92 DPS vs 保底火力 Lv.5 = 107 DPS（保底够 116%）——
 *   **保底能通关，构筑决定余量**（第四轮末的线性伤害改动把这条修回来了；
 *   第五轮重新测量：保底构筑的覆盖度在第 20 波是 ×1.16）。
 *
 * 第五轮为什么**没有**再调这个系数（实测，不是拍脑袋）：
 * 一局的装备来源从 4 次变成 8 次（多了 4 次异变体战利品），构筑明显变强，
 * 本该把系数抬上去；���重新测量之后发现**覆盖度曲线没有漂移**
 * （smart 末段覆盖度 1.35~2.84，与第四轮的 1.08~2.30 同量级；
 *  good 仍然 0/3 通关）⇒ **不动**。
 * 详见 DECISIONS §15.6。
 */
export const ENEMY_HP_PER_WAVE = 2.0;

/**
 * 每一章的**血量台阶**（第八轮加的）。
 *
 * 为什么要有台阶：玩家的强度是**按章台阶**上去的 ——
 * 章节开始火力等级 +1（Lv.2 7 DPS → Lv.3 26 → Lv.4 43 → Lv.5 107，指数轴），
 * 再加章首的装备与异变体战利品。而需求（需求 DPS）此前只是**线性**跟着波次走
 * ⇒ 后面几章玩家越滚越强，需求追不上。
 *
 * 实测（第八轮）：一个**不读标签**的构筑在第 20 波的覆盖度到了 **3.17**
 * （第五轮同一指标是 0.95）⇒ 构筑质量不再决定生死，游戏被做软了。
 *
 * ⇒ 需求也改成**按章台阶**：章内仍是线性的（每波 +1.25），
 * 台阶放在章与章之间 —— **与玩家的台阶对齐**。
 *
 * 数值来历：按「中等构筑（good 机器人）的实测 DPS ÷ 目标覆盖度」反推
 * （需求 = 血量 ÷ 出怪窗口，怪种组合会带 ±10% 的混合噪声，所以是反推区间不是精确解）：
 *   第 5 波 ≈ 3.5 · 第 10 波 ≈ 2.2 · 第 14 波 ≈ 2.2 · **第 16~17 波 ≈ 1.8~2.0** · 第 20 波 ≈ 2.8
 *
 * 台阶之间必须**递增**（b3 ≥ b2 + 4×斜率），否则章与章的交界处
 * 敌人的血量会**倒退**（"越到后面越弱"）。
 *
 * ⚠️ 第八轮调过两轮：
 *   第一版（台阶 [0,24,40,58]、章内斜率 2.0）**太难** ——
 *   连"会构筑"的机器人都死在第 14~15 波（覆盖度 0.87~1.34）。
 *   ⇒ 覆盖度 ~1.0 是**战术致死线**（不是 DPS 不够，是怪太多、挨打多），
 *   所以目标覆盖度要留出余量。
 *   第二版（[0,20,28,36]、斜率 2.0）仍然偏难（会构筑的机器人死在第 14~18 波）。
 *   第三版（[0,16,22,28]、斜率 1.25）依然偏难（死在第 17 波，只差 1 点血）。
 *   第四版（[0,12,18,26]）死在第 19 波（同样只差 1 点血）。
 *   **定稿**：[0,12,18,23]、章内斜率 1.25 ——
 *   会构筑的构筑在第四章开头的覆盖度约 2.2（留出余量，但仍是全程最难的一段）。
 *
 *   ⚠️ 还有一条更重要的实测教训（见 DECISIONS §21.5.4）：
 *   **"会构筑"与"按稀有度挑"两种构筑的 DPS 只差 10~30%**，
 *   所以**不存在一条需求曲线能把它们分开** ——
 *   难度只能定在"两边都能过、但都会翻车"的区间（靠方差提供紧张感），
 *   构筑质量的差别体现在**走得更深、分数更高**，而不是"谁通关"。
 * —— 也就是**第四章开头有一个"掉队区"**（覆盖度跌破 1），
 * 而一个**保底构筑**（只吃章节保底火力、不抽任何伤害牌）在第三章就撑不住。
 * ⇒ 「构筑决定生死」重新变成真的：**中期宽（构筑起效）、后期紧（最后一章是考试）**。
 */
/**
 * 章间台阶改成**乘法**（第九轮最后一次改数值时推翻的）。
 *
 * 为什么从「绝对加值」改成「倍率」：
 * 绝对加值在**章交界处会暴增** ——
 * 实测（第九轮 ×2.0 版）：第 5 波需求 14 → 第 6 波需求 **57（×4）**，
 * 而玩家在第 6 波只是 Lv.2（15 DPS）⇒ 覆盖度 0.26 ⇒ **一个机器人直接死在第 7 波**。
 *
 * 原因：第一章末的怪只有 ~9 点血（章内才涨了 8 点），
 * 而"加 32"这种绝对台阶相对它太大了 ⇒ 需求在章节边界上跳一级台阶。
 *
 * ⇒ 改成**每章 ×1.35**（上一章末的血量 ×1.35 = 下一章第一波），
 * 章内仍是线性 ⇒ 需求曲线**平滑爬升，不在章交界处跳**。
 *
 * 形状：**第二章宽（玩家还没成型）→ 第三章是悬崖 → 第四章是考试**。
 */
export const CHAPTER_HP_MUL = 1.35;

/**
 * 各章**第一波**的血量成长（递归：上一章末 × CHAPTER_HP_MUL）。
 * 索引 0 = 第一章。
 */
export const CHAPTER_HP_BASE = (() => {
  const out = [0];
  for (let i = 1; i < 12; i++) {
    const prevEnd = out[i - 1] + 4 * ENEMY_HP_PER_WAVE;
    out.push(Math.floor(prevEnd * CHAPTER_HP_MUL));
  }
  return out;
})();

/** 旧的绝对台阶（保留导出以便对照，实测已不用于计算） */
export const CHAPTER_HP_BONUS = CHAPTER_HP_BASE;

/**
 * 各章 Boss 的**总血量**（第九轮重做）。
 *
 * ⚠️ 为什么重做（这是第九轮查出来的真问题）：
 * 旧公式 `40 + 波次² × 1.6` 是**按"保底火力 107 DPS"标定**的
 * （注释里写的就是"1440 ÷ 107 ≈ 13 秒"）。
 * 但第八轮实测：**玩家在第 20 波的真实 DPS 是 178~298**（不是 107）——
 * 章节保底火力之外，8 次装备挑选 + 路线给的潮水把 DPS 抬到了保底线的 2~3 倍。
 * ⇒ **标定会过期**（第二次踩同一个坑，见 §21.5.2）：
 * 终局 Boss 720×2 = 1440 血，在 200 DPS 下 **7 秒就死** ——
 * **三阶段机制根本来不及登场，Boss 战从"考试"退化成"过场动画"**。
 * 而且更糟的是：`waveDpsNeed` **从来没把 Boss 血量算进需求**，
 * 所以覆盖度这把尺子**从来没测到过 Boss**（第九轮一并修了）。
 *
 * 新表的来历：**按实测 DPS × 目标战斗时长反推**（第八轮 balance 报告）：
 * | 章 | 波 | 实测玩家 DPS | 目标时长 | Boss 血量 |
 * |---|---|---|---|---|
 * | 1 | w5  | 37 ~ 107（中位 65） | ~11 秒 | 700 |
 * | 2 | w10 | 108 ~ 167（中位 140） | ~9 秒 | 1300 |
 * | 3 | w15 | 150 ~ 194（中位 175） | ~10 秒 | 1700 |
 * | 4 | w20 | 178 ~ 298（中位 200） | 终局 ×2 ⇒ ~20 秒 | 2000 |
 *
 * ⇒ 终局 Boss = 2000 × 2.0 = **4000 血**，中位构筑要打 **20 秒**
 * （保底构筑 107 DPS 要打 37 秒 ⇒ 它本来就该输）。
 */
export const BOSS_HP_BY_CHAPTER = [1540, 2860, 3740, 4400];

/** 无尽模式：Boss 血量每章递增多少（表尾外推用） */
export const BOSS_HP_STEP = 300;

/**
 * 第 chapterIndex 章（1 起）的 Boss 总血量。
 *
 * 为什么是"按章查表"而不是"按波次算公式"：
 * Boss 只在每章最后一波出现 ⇒ 没有章内插值的需求，
 * 而**表能直接写清楚每一场的目标战斗时长**（比一条曲线好读也好改）。
 */
export function bossHpForChapter(chapterIndex) {
  const idx = Math.max(1, Math.floor(chapterIndex));
  const last = BOSS_HP_BY_CHAPTER.length;          // 4
  if (idx <= last) return BOSS_HP_BY_CHAPTER[idx - 1];
  // 表尾外推：每多一章 +BOSS_HP_STEP（用最后两档的差值，与 CHAPTER_HP_BONUS 同一套做法）
  const step = BOSS_HP_BY_CHAPTER[last - 1] - BOSS_HP_BY_CHAPTER[last - 2];
  return BOSS_HP_BY_CHAPTER[last - 1] + (idx - last) * step;
}

/**
 * 终局 Boss 的额外血量倍率。
 *
 * 终局 Boss = 2000 × 2.0 = **4000 血**：中位构筑 200 DPS 要打 20 秒，
 * 保底构筑 107 DPS 要打 37 秒 —— **最终决战真的是构筑的考试**
 * （第八轮它是 7 秒纸糊，见上面那段"为什么重做"）。
 */
export const FINAL_BOSS_HP_MUL = 2.0;

/**
 * 章节开始时的火力保底：+1 级（见 systems/upgrades.js 的 chapterStartFire）。
 * **这是"保证一局走得完"的底线**，调低它会重演 §6.6 的死亡螺旋。
 */
export const FIRE_PER_CHAPTER = 1;

/**
 * 评级的分数门槛（通关时按得分分档，失败时按清章数分档）。
 *
 * **重算过两次**：
 * 1. 旧门槛 9000 —— 平衡测量里一局 45,000~70,000 分，会让所有人都拿 S。
 * 2. 60000/40000/25000 —— 那批数据里**分数被"一次击杀记成两次"的 bug 灌了水**（§14.5）。
 * 3. 现在这组基于**修好重复计分 bug 之后**的实测（balance 报告，good 机器人）：
 *    第 20 波阵亡 ≈ 57,000；打到第 27 波（无尽模式）≈ 97,000~135,000。
 *    → 一次典型的通关（打到第 20 波）落在 60,000~75,000，
 *      所以 A 放在 65,000；打进无尽模式的 S 放在 90,000。
 */
export const GRADE_THRESHOLDS = { S: 90000, A: 65000, B: 45000 };
